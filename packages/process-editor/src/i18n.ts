export type Lang = 'pt' | 'en';
const dicts: Record<Lang, Dict> = { pt, en };

interface LangState { lang: Lang; setLang: (l: Lang) => void }
const initial: Lang = (() => { try { return (localStorage.getItem('ps-lang') as Lang) || (navigator.language.startsWith('en') ? 'en' : 'pt'); } catch { return 'pt'; } })();
export const useLang = create<LangState>((set) => ({
  lang: initial,
  setLang: (lang) => { try { localStorage.setItem('ps-lang', lang); } catch { /* storage indisponível: só não persiste */ } set({ lang }); },
}));

export const useT = (): Dict => dicts[useLang((s) => s.lang)];
/** Para código fora de componentes (store): dicionário atual sem hook. */
export const currentT = (): Dict => dicts[useLang.getState().lang];
